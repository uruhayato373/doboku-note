/** frontmatter の description（同一行 / `>` `|` の折り返しブロック）を 1 つの文字列に */
function frontmatterDescription(fmBlock) {
  const inner = fmBlock.split('\n').slice(1, -1);
  const idx = inner.findIndex((l) => /^description\s*:/.test(l));
  if (idx === -1) return null;
  const head = inner[idx].replace(/^description\s*:/, '').trim();
  if (!/^[>|][-+]?$/.test(head)) return head.replace(/^(["'])(.*)\1$/, '$2');
  const parts = [];
  for (const l of inner.slice(idx + 1)) {
    if (!/^\s+\S/.test(l)) break;
    parts.push(l.trim());
  }
  return parts.join(head.startsWith('|') ? '\n' : ' ').trim();
}

const CONTROL_CHARS = /[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g;
const uEscape = (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`;
const tomlBasic = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(CONTROL_CHARS, uEscape).replace(/\r?\n/g, '\\n').replace(/\t/g, '\\t') + '"';
// 複数行 basic string。`\` はエスケープ、`"""` は `""\"` に割る（3 連続の `"` を作らない）。改行は LF に正規化
const tomlMultiline = (s) => '"""\n' + String(s).replace(/\r\n/g, '\n').replace(/\\/g, '\\\\').replace(/"""/g, '""\\"').replace(CONTROL_CHARS, uEscape).replace(/\n*$/, '') + '\n"""\n';

/**
 * .claude/agents/<name>.md → .codex/agents/<name>.toml（name / description / developer_instructions）。
 * 本文は原文のまま（`.claude/` パスを書き換えない。Codex も同じ repo を読む）。
 * @returns {{ name: string, content: string } | { error: string }}
 */
function buildAgentToml(agentPath, content) {
  const fm = extractFrontmatterBlock(content);
  const name = fm && frontmatterScalar(fm, 'name');
  const description = fm && frontmatterDescription(fm);
  if (!fm || !name || !description) return { error: 'invalid-frontmatter' };
  const expectedName = agentPath.slice(agentPath.lastIndexOf('/') + 1, -'.md'.length);
  if (name !== expectedName) return { error: `name-mismatch（frontmatter name=${name} / file=${expectedName}）` };
  const body = stripFrontmatter(content).replace(/\r\n/g, '\n');
  return { name, content: AGENT_TOML_BANNER + `name = ${tomlBasic(name)}\ndescription = ${tomlBasic(description)}\ndeveloper_instructions = ${tomlMultiline(body)}` };
}

/**
 * .claude/settings.json の hooks → .codex/hooks.json。SessionStart は Codex に無いので落とす。
 * command は相対パスの `node scripts/hooks/agent-hook.mjs <name>` 等に限る（絶対パスは Mac/Windows の片方でしか動かない）。
 * @returns {{ content: string | null, errors: string[], commands: string[] }}
 */
function buildCodexHooks(settingsText) {
  const errors = [];
  let settings;
  try {
    settings = JSON.parse(stripBom(settingsText));
  } catch (e) {
    return { content: null, errors: [`${CLAUDE_SETTINGS}: JSON として読めない（${e.message}）`], commands: [] };
  }
  const hooks = {};
  const commands = [];
  for (const [event, groups] of Object.entries(settings.hooks || {})) {
    if (event === 'SessionStart') continue;
    hooks[event] = groups.map((g) => {
      const out = {};
      if (g.matcher) out.matcher = g.matcher;
      out.hooks = (g.hooks || []).map((h) => {
        const entry = { type: h.type, command: h.command };
        if (h.timeout) entry.timeout = h.timeout;
        commands.push(h.command);
        if (/(^|\s|['"])(\/Users\/|\/home\/|[A-Za-z]:[\\/])/.test(h.command)) errors.push(`${event}: 絶対パスの command は片方の OS でしか動かない: ${h.command}`);
        return entry;
      });
      return out;
    });
  }
  return { content: JSON.stringify({ hooks }, null, 2) + '\n', errors, commands };
}

/** hooks の command が指すスクリプト（`node <path>` / `<path>.sh`）を取り出す */
function hookCommandTargets(commands) {
  const out = new Set();
  for (const c of commands) {
    const m = c.match(/(?:^|\s)node\s+((?:\.?\/)?[\w./-]+\.(?:mjs|cjs|js))/) || c.match(/(?:^|\s)((?:\.?\/)?[\w./-]+\.sh)/);
    if (m) out.add(m[1].replace(/^\.\//, ''));
  }
  return [...out];
}

function buildSkillShim(fmBlock, skillPath, relDir) {
  const body =
    SKILL_BANNER +
    '\n' +
    `Canonical skill instructions: \`${skillPath}\`\n\n` +
    'Before taking any task action, read the canonical SKILL.md completely and follow it as the single source of truth.\n' +
    `Resolve every relative reference, script, asset, template, and reference file from the canonical \`${CLAUDE_SKILLS_DIR}/${relDir}/\` directory.\n` +
    `Do not read or execute sibling payload files from \`${AGENTS_SKILLS_DIR}/\`; this file is only a Codex discovery entrypoint.\n`;
  return `${fmBlock}\n\n${body}`;
}

// canonicalEntries: [{ skillPath, relDir, content }]（symlink は呼び出し側で既に除外済み）
// ruleEntries: [{ path, content }]（.claude/rules/**/*.md・symlink 除外済み）
// 戻り値: { agentsMdExpected, skillExpected: Map<agentsPath, content>, errors: [{type,...}] }
function buildExpected(claudeMdContent, canonicalEntries, ruleEntries = []) {
  const errors = [];
  const skillExpected = new Map();
  const seenNames = new Map();

  for (const entry of canonicalEntries) {
    const fm = extractFrontmatterBlock(entry.content);
    const name = fm && frontmatterScalar(fm, 'name');
    const hasDescription = fm && frontmatterHasKey(fm, 'description');
    if (!fm || !name || !hasDescription) {
      errors.push({ type: 'invalid-frontmatter', path: entry.skillPath });
      continue;
    }
    if (!seenNames.has(name)) seenNames.set(name, []);
    seenNames.get(name).push(entry.skillPath);

    const agentsPath = `${AGENTS_SKILLS_DIR}/${entry.relDir}/SKILL.md`;
    skillExpected.set(agentsPath, buildSkillShim(fm, entry.skillPath, entry.relDir));
  }

  for (const [name, paths] of seenNames) {
    if (paths.length > 1) errors.push({ type: 'duplicate-name', name, paths });
  }

  const rulesSection = buildRulesSection(ruleEntries, errors);
  // CLAUDE.md が改行で終わっていなくても rules 節の前に空行を 1 つ確保する
  const claudeBody = rulesSection && !/\r?\n$/.test(claudeMdContent) ? claudeMdContent + '\n' : claudeMdContent;

  return {
    // バナーは LF 固定だが CLAUDE.md は作業ツリーでは CRLF（core.autocrlf=true）。
    // そのまま連結すると生成のたびに AGENTS.md が CRLF/LF 混在になる。git が commit 時に
    // 正規化するので blob は汚れないが、作業ツリーを走査する検査には毎回引っかかる
    // （2026-08-28 の混在棚卸しで実際に検出された）。本文の EOL に合わせて出力する（rules 節も同じ）。
    agentsMdExpected: matchEol(AGENTS_MD_BANNER, claudeMdContent) + claudeBody + matchEol(rulesSection, claudeMdContent),
    skillExpected,
    errors,
  };
}

// ---- filesystem source（--check 既定 / --write） ------------------------------------------------

function walkFs(dir, onSymlink) {
  const out = [];
  if (!existsSync(dir)) return out;
  const stack = [dir];
  while (stack.length) {
    const d = stack.pop();
    for (const e of readdirSync(d)) {
      const p = join(d, e);
      const rp = relRoot(p);
      if (WALK_IGNORE.has(rp)) continue;
      const st = lstatSync(p);
      if (st.isSymbolicLink()) {
        onSymlink?.(rp);
        continue;
      }
      if (st.isDirectory()) stack.push(p);
      else out.push(rp);
    }
  }
  return out;
}

