function toPosix(p) {
  return p.split(sep).join('/');
}

function relRoot(absPath) {
  return toPosix(relative(ROOT, absPath));
}

function stripBom(s) {
  return s.replace(/^﻿/, '');
}

// ---- frontmatter（軽量・line-based。フル YAML パーサは導入しない） -------------------------------

function extractFrontmatterBlock(content) {
  const lines = stripBom(content).split(/\r?\n/);
  if (lines[0] !== '---') return null;
  const end = lines.indexOf('---', 1);
  if (end === -1) return null;
  return lines.slice(0, end + 1).join('\n');
}

function frontmatterScalar(fmBlock, key) {
  const inner = fmBlock.split('\n').slice(1, -1);
  const idx = inner.findIndex((l) => new RegExp(`^${key}\\s*:`).test(l));
  if (idx === -1) return null;
  return inner[idx].replace(new RegExp(`^${key}\\s*:`), '').trim();
}

function frontmatterHasKey(fmBlock, key) {
  return fmBlock.split('\n').slice(1, -1).some((l) => new RegExp(`^${key}\\s*:`).test(l));
}

/** rule の frontmatter から paths: のパターン一覧を取り出す（ブロック形式 / インライン `[a, b]` の両方） */
function frontmatterPaths(fmBlock) {
  const inner = fmBlock.split('\n').slice(1, -1);
  const idx = inner.findIndex((l) => /^paths\s*:/.test(l));
  if (idx === -1) return [];
  const inline = inner[idx].replace(/^paths\s*:/, '').trim();
  if (inline) {
    return inline.replace(/^\[|\]$/g, '').split(',').map((s) => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
  }
  const out = [];
  for (const l of inner.slice(idx + 1)) {
    const m = l.match(/^\s+-\s+(.+)$/);
    if (!m) break;
    out.push(m[1].trim().replace(/^["']|["']$/g, ''));
  }
  return out;
}

function stripFrontmatter(content) {
  const lines = stripBom(content).split(/\r?\n/);
  if (lines[0] !== '---') return lines.join('\n');
  const end = lines.indexOf('---', 1);
  if (end === -1) return lines.join('\n');
  return lines.slice(end + 1).join('\n').replace(/^\n+/, '');
}

// rules の相対リンクは .claude/rules/ 起点（`../knowledge/...` / `../../docs/...`）。AGENTS.md はルート直下なので
// そのまま併合すると href が壊れ check-relative-links に掛かる。ルート起点へ書き換える（順序: `../../` を先に）。
function rewriteRuleLinks(body) {
  return body.replace(/\]\(\.\.\/\.\.\//g, '](./').replace(/\]\(\.\.\//g, '](./.claude/');
}

// ruleEntries: [{ path, content }] → { section: string (LF), errors }
function buildRulesSection(ruleEntries, errors) {
  const parts = [];
  for (const rule of ruleEntries) {
    const fm = extractFrontmatterBlock(rule.content);
    const paths = fm ? frontmatterPaths(fm) : [];
    if (!paths.length) {
      errors.push({ type: 'rule-without-paths', path: rule.path });
      continue;
    }
    const body = rewriteRuleLinks(stripFrontmatter(rule.content)).trimEnd();
    parts.push(`### ${rule.path}\n\n適用パス: ${paths.map((p) => `\`${p}\``).join(', ')}\n\n${body}\n`);
  }
  if (!parts.length) return '';
  return `\n${RULES_SECTION_HEADING}\n\n${parts.join('\n')}`;
}

