// ---- git index source（--staged） ----------------------------------------------------------------

function gitIndexEntries(pathspec) {
  let out;
  try {
    out = execFileSync(
      'git',
      ['-c', 'core.quotepath=false', 'ls-files', '--stage', '--', pathspec],
      { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, cwd: ROOT },
    );
  } catch (e) {
    throw new Error(`git ls-files failed for ${pathspec}: ${e.message}`);
  }
  return out
    .split('\n')
    .filter(Boolean)
    .map((line) => {
      const tab = line.indexOf('\t');
      const [mode, sha] = line.slice(0, tab).trim().split(/\s+/);
      return { mode, sha, path: line.slice(tab + 1) };
    });
}

function catFile(sha) {
  return execFileSync('git', ['cat-file', '-p', sha], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, cwd: ROOT });
}

function indexSource() {
  let agentsShaByPath = null;
  let codexShaByPath = null;
  return {
    label: 'git index (staged)',
    readClaudeMd() {
      const [e] = gitIndexEntries(CLAUDE_MD);
      return e ? catFile(e.sha) : null;
    },
    readAgentsMd() {
      const [e] = gitIndexEntries(AGENTS_MD);
      return e ? catFile(e.sha) : null;
    },
    listCanonicalSkills() {
      const all = gitIndexEntries(CLAUDE_SKILLS_DIR);
      const skillEntries = all.filter((e) => e.path.endsWith('/SKILL.md'));
      const symlinks = skillEntries.filter((e) => e.mode === '120000').map((e) => e.path).sort();
      const entries = skillEntries
        .filter((e) => e.mode !== '120000')
        .map((e) => ({
          skillPath: e.path,
          relDir: e.path.slice(CLAUDE_SKILLS_DIR.length + 1, -'/SKILL.md'.length),
          content: catFile(e.sha),
        }))
        .sort((a, b) => (a.skillPath < b.skillPath ? -1 : 1));
      return { entries, symlinks };
    },
    listRules() {
      const all = gitIndexEntries(RULES_DIR).filter((e) => e.path.endsWith('.md'));
      const symlinks = all.filter((e) => e.mode === '120000').map((e) => e.path).sort();
      const entries = all
        .filter((e) => e.mode !== '120000')
        .map((e) => ({ path: e.path, content: catFile(e.sha) }))
        .sort((a, b) => (a.path < b.path ? -1 : 1));
      return { entries, symlinks };
    },
    listAgentsSkillsFiles() {
      const entries = gitIndexEntries(AGENTS_SKILLS_DIR);
      agentsShaByPath = new Map(entries.map((e) => [e.path, e.sha]));
      const symlinks = entries.filter((e) => e.mode === '120000').map((e) => e.path).sort();
      const files = entries.map((e) => e.path).sort();
      return { files, symlinks };
    },
    readAgentsSkillFile(p) {
      const sha = agentsShaByPath?.get(p);
      if (!sha) throw new Error(`not in index: ${p}`);
      return catFile(sha);
    },
    listClaudeAgents() {
      const all = gitIndexEntries(CLAUDE_AGENTS_DIR).filter((e) => e.path.endsWith('.md') && !e.path.slice(CLAUDE_AGENTS_DIR.length + 1).includes('/'));
      const symlinks = all.filter((e) => e.mode === '120000').map((e) => e.path).sort();
      const entries = all
        .filter((e) => e.mode !== '120000')
        .map((e) => ({ path: e.path, content: catFile(e.sha) }))
        .sort((a, b) => (a.path < b.path ? -1 : 1));
      return { entries, symlinks };
    },
    listCodexAgentFiles() {
      const entries = gitIndexEntries(CODEX_AGENTS_DIR);
      codexShaByPath = new Map(entries.map((e) => [e.path, e.sha]));
      const symlinks = entries.filter((e) => e.mode === '120000').map((e) => e.path).sort();
      return { files: entries.map((e) => e.path).sort(), symlinks };
    },
    readCodexAgentFile(p) {
      const sha = codexShaByPath?.get(p);
      if (!sha) throw new Error(`not in index: ${p}`);
      return catFile(sha);
    },
    readClaudeSettings() {
      const [e] = gitIndexEntries(CLAUDE_SETTINGS);
      return e ? catFile(e.sha) : null;
    },
    readCodexHooks() {
      const [e] = gitIndexEntries(CODEX_HOOKS_JSON);
      return e ? catFile(e.sha) : null;
    },
    fileExists(rel) {
      return gitIndexEntries(rel).length > 0;
    },
  };
}

// ---- runtime consumer 走査（常に working tree・モードに依らない） ---------------------------------

function scanRuntimeConsumers() {
  const files = [];
  for (const root of RUNTIME_SCAN_ROOTS) {
    const abs = join(ROOT, root);
    if (!existsSync(abs)) continue;
    const st = lstatSync(abs);
    if (st.isSymbolicLink()) continue;
    if (st.isDirectory()) {
      files.push(...walkFs(abs).filter((p) => TEXT_EXT.has(p.slice(p.lastIndexOf('.')))));
    } else {
      files.push(relRoot(abs));
    }
  }
  const uniq = [...new Set(files)].sort();
  const hits = [];
  for (const f of uniq) {
    if (RUNTIME_CONSUMER_ALLOWLIST.has(f)) continue;
    let text;
    try {
      text = readFileSync(join(ROOT, f), 'utf8');
    } catch {
      continue;
    }
    if (text.includes(`${AGENTS_SKILLS_DIR}/`)) hits.push(f);
  }
  return { scanned: uniq, hits };
}

// ---- 比較 + レポート -------------------------------------------------------------------------

function runCheck(source) {
  const claudeMdContent = source.readClaudeMd();
  if (claudeMdContent === null) {
    console.error(`[check-codex-compat] ✗ ${CLAUDE_MD} が見つかりません（${source.label}）`);
    return 1;
  }

  let canonical;
  let agentsListing;
  let rules;
  try {
    canonical = source.listCanonicalSkills();
    agentsListing = source.listAgentsSkillsFiles();
    rules = source.listRules();
  } catch (e) {
    console.error(`[check-codex-compat] ✗ 取得失敗: ${e.message}`);
    return 1;
  }

  if (canonical.entries.length === 0 && canonical.symlinks.length === 0) {
    console.error(`[check-codex-compat] ✗ canonical SKILL.md が 0 件（${CLAUDE_SKILLS_DIR} の取得に失敗した可能性）`);
    return 1;
  }

  const canonicalBytes = canonical.entries.reduce((n, e) => n + Buffer.byteLength(e.content, 'utf8'), 0);
  const { agentsMdExpected, skillExpected, errors } = buildExpected(claudeMdContent, canonical.entries, rules.entries);

  const agentsFilesSet = new Set(agentsListing.files);
  const missingSkills = [];
  // 生成物は git が LF で保存し、autocrlf の作業ツリーでは CRLF に展開される。
  // バイト厳密に比べると **clone / git checkout しただけで mismatch** になり、しかも
  // git 側は正規化して差分ゼロに見せるので原因に辿り着けない（2026-08-31 実測）。
  // 中身が同じかを見たいので、比較の前に改行だけ揃える。
  const sameContent = (a, b) =>
    String(a).split('\r\n').join('\n') === String(b).split('\r\n').join('\n');

  const mismatchSkills = [];
  const readFailures = [];
  let generatedBytes = 0;
  let presentCount = 0;

  for (const [agentsPath, expectedContent] of skillExpected) {
    if (!agentsFilesSet.has(agentsPath)) {
      missingSkills.push(agentsPath);
      continue;
    }
    let actual;
    try {
      actual = source.readAgentsSkillFile(agentsPath);
    } catch (e) {
      readFailures.push(`${agentsPath}: ${e.message}`);
      continue;
    }
    presentCount++;
    generatedBytes += Buffer.byteLength(actual, 'utf8');
    if (!sameContent(actual, expectedContent)) mismatchSkills.push(agentsPath);
  }

  const extra = agentsListing.files.filter((p) => !skillExpected.has(p));

  // ---- .claude/agents/*.md → .codex/agents/*.toml ----
  const claudeAgents = source.listClaudeAgents();
  const codexAgents = source.listCodexAgentFiles();
  const agentExpected = new Map();
  const agentErrors = [];
  for (const a of claudeAgents.entries) {
    const built = buildAgentToml(a.path, a.content);
    if (built.error) agentErrors.push(`${a.path}: ${built.error}`);
    else agentExpected.set(`${CODEX_AGENTS_DIR}/${built.name}.toml`, built.content);
  }
  const codexFilesSet = new Set(codexAgents.files);
  const agentMissing = [...agentExpected.keys()].filter((p) => !codexFilesSet.has(p));
  const agentExtra = codexAgents.files.filter((p) => !agentExpected.has(p));
  const agentMismatch = [];
  let agentPresent = 0;
  for (const [p, expected] of agentExpected) {
    if (!codexFilesSet.has(p)) continue;
    agentPresent++;
    if (!sameContent(source.readCodexAgentFile(p), expected)) agentMismatch.push(p);
  }

  // ---- .claude/settings.json hooks → .codex/hooks.json ----
  const settingsText = source.readClaudeSettings();
  const hooksBuilt = settingsText === null ? { content: null, errors: [`${CLAUDE_SETTINGS} が無い`], commands: [] } : buildCodexHooks(settingsText);
  const hookErrors = [...hooksBuilt.errors];
  for (const target of hookCommandTargets(hooksBuilt.commands)) if (!source.fileExists(target)) hookErrors.push(`hook が指すスクリプトが無い: ${target}`);
  const codexHooksActual = source.readCodexHooks();
  let hooksStatus = 'ok';
  if (hooksBuilt.content === null) hooksStatus = 'unbuildable';
  else if (codexHooksActual === null) hooksStatus = 'missing';
  else if (!sameContent(codexHooksActual, hooksBuilt.content)) hooksStatus = 'mismatch';

  const agentsMdActual = source.readAgentsMd();
  let agentsMdStatus = 'ok';
  let agentsMdMissing = false;
  let agentsMdMismatch = false;
  if (agentsMdActual === null) {
    agentsMdStatus = 'missing';
    agentsMdMissing = true;
  } else if (!sameContent(agentsMdActual, agentsMdExpected)) {
    agentsMdStatus = 'mismatch';
    agentsMdMismatch = true;
  }

  const runtime = scanRuntimeConsumers();

  const fmInvalid = errors.filter((e) => e.type === 'invalid-frontmatter');
  const dupNames = errors.filter((e) => e.type === 'duplicate-name');
  const ruleNoPaths = errors.filter((e) => e.type === 'rule-without-paths');
  const symlinks = [...canonical.symlinks, ...agentsListing.symlinks, ...rules.symlinks];

  console.log(`[check-codex-compat] source=${source.label}`);
  console.log(`[check-codex-compat] canonical SKILL.md: ${canonical.entries.length} 件（検査 ${canonicalBytes} bytes）`);
  console.log(`[check-codex-compat] ${RULES_DIR}: ${rules.entries.length} 件（AGENTS.md へ併合・paths 無し ${ruleNoPaths.length}）`);
  console.log(`[check-codex-compat] .agents/skills 実ファイル: ${agentsListing.files.length} 件（生成対象一致 ${presentCount} 件・検査 ${generatedBytes} bytes）`);
  console.log(`[check-codex-compat] AGENTS.md: ${agentsMdStatus}`);
  console.log(
    `[check-codex-compat] missing=${missingSkills.length}${agentsMdMissing ? '+AGENTS.md' : ''} ` +
      `extra=${extra.length} mismatch=${mismatchSkills.length}${agentsMdMismatch ? '+AGENTS.md' : ''} ` +
      `frontmatter不成立=${fmInvalid.length} skill名重複=${dupNames.length} symlink=${symlinks.length} read失敗=${readFailures.length}`,
  );
  console.log(`[check-codex-compat] runtime consumer 走査対象: ${runtime.scanned.length} ファイル / ヒット: ${runtime.hits.length} 件`);
  console.log(`[check-codex-compat] ${CLAUDE_AGENTS_DIR}: ${claudeAgents.entries.length} 件 → ${CODEX_AGENTS_DIR}: 実ファイル ${codexAgents.files.length} 件（一致 ${agentPresent - agentMismatch.length} / missing ${agentMissing.length} / extra ${agentExtra.length} / mismatch ${agentMismatch.length} / frontmatter不成立 ${agentErrors.length}）`);
  console.log(`[check-codex-compat] ${CODEX_HOOKS_JSON}: ${hooksStatus}（hook command ${hooksBuilt.commands.length} 件・問題 ${hookErrors.length}）`);

  const problems = [];
  if (missingSkills.length) problems.push(`missing:\n${missingSkills.map((p) => `  - ${p}`).join('\n')}`);
  if (agentsMdMissing) problems.push(`missing:\n  - ${AGENTS_MD}`);
  if (extra.length) problems.push(`extra:\n${extra.map((p) => `  - ${p}`).join('\n')}`);
  if (mismatchSkills.length) problems.push(`mismatch:\n${mismatchSkills.map((p) => `  - ${p}`).join('\n')}`);
  if (agentsMdMismatch) problems.push(`mismatch:\n  - ${AGENTS_MD}`);
  if (readFailures.length) problems.push(`read failure:\n${readFailures.map((p) => `  - ${p}`).join('\n')}`);
  if (fmInvalid.length) problems.push(`frontmatter不成立:\n${fmInvalid.map((e) => `  - ${e.path}`).join('\n')}`);
  if (dupNames.length) problems.push(`skill名重複:\n${dupNames.map((e) => `  - ${e.name}: ${e.paths.join(', ')}`).join('\n')}`);
  if (symlinks.length) problems.push(`symlink:\n${symlinks.map((p) => `  - ${p}`).join('\n')}`);
  if (ruleNoPaths.length) problems.push(`rule-without-paths（paths: 無しの rule は常時読み込みになる。領域を限定できないなら CLAUDE.md へ）:\n${ruleNoPaths.map((e) => `  - ${e.path}`).join('\n')}`);
  if (runtime.hits.length) problems.push(`runtime consumer（${AGENTS_SKILLS_DIR}/ 直接参照）:\n${runtime.hits.map((p) => `  - ${p}`).join('\n')}`);
  if (agentMissing.length) problems.push(`codex agent missing:\n${agentMissing.map((p) => `  - ${p}`).join('\n')}`);
  if (agentExtra.length) problems.push(`codex agent extra（正典 ${CLAUDE_AGENTS_DIR} に無い）:\n${agentExtra.map((p) => `  - ${p}`).join('\n')}`);
  if (agentMismatch.length) problems.push(`codex agent mismatch:\n${agentMismatch.map((p) => `  - ${p}`).join('\n')}`);
  if (agentErrors.length) problems.push(`agent frontmatter不成立:\n${agentErrors.map((p) => `  - ${p}`).join('\n')}`);
  if (claudeAgents.symlinks.length || codexAgents.symlinks.length) problems.push(`agent symlink:\n${[...claudeAgents.symlinks, ...codexAgents.symlinks].map((p) => `  - ${p}`).join('\n')}`);
  if (hooksStatus !== 'ok') problems.push(`${CODEX_HOOKS_JSON}: ${hooksStatus}`);
  if (hookErrors.length) problems.push(`hooks:\n${hookErrors.map((p) => `  - ${p}`).join('\n')}`);

  const fail =
    canonical.entries.length === 0 ||
    runtime.scanned.length === 0 ||
    missingSkills.length > 0 ||
    agentsMdMissing ||
    extra.length > 0 ||
    mismatchSkills.length > 0 ||
    agentsMdMismatch ||
    fmInvalid.length > 0 ||
    dupNames.length > 0 ||
    symlinks.length > 0 ||
    readFailures.length > 0 ||
    ruleNoPaths.length > 0 ||
    runtime.hits.length > 0 ||
    claudeAgents.entries.length === 0 ||
    agentMissing.length > 0 ||
    agentExtra.length > 0 ||
    agentMismatch.length > 0 ||
    agentErrors.length > 0 ||
    claudeAgents.symlinks.length > 0 ||
    codexAgents.symlinks.length > 0 ||
    hooksStatus !== 'ok' ||
    hookErrors.length > 0;

  if (fail) {
    console.error(`[check-codex-compat] ✗ FAIL\n${problems.join('\n')}`);
    console.error('\n対処: node scripts/sync-codex-compat.mjs --write で再生成する（frontmatter不成立/skill名重複/symlink/rule-without-paths/絶対パスの hook は先に手で直す）。');
    return 1;
  }
  console.log(`[check-codex-compat] ✓ PASS — AGENTS.md / .agents/skills / ${CODEX_AGENTS_DIR} / ${CODEX_HOOKS_JSON} は CLAUDE.md + .claude/rules / .claude/skills / .claude/agents / .claude/settings.json と同期している`);
  return 0;
}

// ---- --write ---------------------------------------------------------------------------------

function assertUnderAgentsSkills(absPath) {
  const rel = relative(join(ROOT, AGENTS_SKILLS_DIR), absPath);
  if (rel.startsWith('..') || isAbsolute(rel)) {
    throw new Error(`削除対象が ${AGENTS_SKILLS_DIR} 配下ではない: ${absPath}`);
  }
}

function pruneEmptyDirs(startAbsDir) {
  const stopAbs = join(ROOT, AGENTS_SKILLS_DIR);
  let dir = startAbsDir;
  while (dir.startsWith(stopAbs) && dir !== stopAbs) {
    if (!existsSync(dir)) {
      dir = dirname(dir);
      continue;
    }
    if (readdirSync(dir).length > 0) break;
    rmdirSync(dir);
    dir = dirname(dir);
  }
}

function runWrite() {
  const source = fsSource();
  const claudeMdContent = source.readClaudeMd();
  if (claudeMdContent === null) {
    console.error(`[sync-codex-compat] ✗ ${CLAUDE_MD} が見つかりません`);
    return 1;
  }
  const canonical = source.listCanonicalSkills();
  if (canonical.entries.length === 0) {
    console.error(`[sync-codex-compat] ✗ canonical SKILL.md が 0 件。書き込みを中止`);
    return 1;
  }
  if (canonical.symlinks.length) {
    console.error(`[sync-codex-compat] ✗ ${CLAUDE_SKILLS_DIR} 配下に symlink がある。書き込みを中止:`);
    for (const p of canonical.symlinks) console.error(`  - ${p}`);
    return 1;
  }
  const rules = source.listRules();
  if (rules.symlinks.length) {
    console.error(`[sync-codex-compat] ✗ ${RULES_DIR} 配下に symlink がある。書き込みを中止:`);
    for (const p of rules.symlinks) console.error(`  - ${p}`);
    return 1;
  }
  const { agentsMdExpected, skillExpected, errors } = buildExpected(claudeMdContent, canonical.entries, rules.entries);
  if (errors.length) {
    console.error('[sync-codex-compat] エラーがある canonical skill / rule は生成対象から除外して続行:');
    for (const e of errors) console.error(`  - ${e.type}: ${e.path ?? `${e.name}: ${e.paths.join(', ')}`}`);
  }

  let written = 0;
  let unchanged = 0;
  for (const [agentsPath, expected] of skillExpected) {
    const abs = join(ROOT, agentsPath);
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    if (current === expected) {
      unchanged++;
      continue;
    }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, expected, 'utf8');
    written++;
  }

  const currentAgents = source.listAgentsSkillsFiles();
  if (currentAgents.symlinks.length) {
    console.error(`[sync-codex-compat] ✗ ${AGENTS_SKILLS_DIR} 配下に symlink がある。削除フェーズを中止:`);
    for (const p of currentAgents.symlinks) console.error(`  - ${p}`);
    return 1;
  }
  let deleted = 0;
  for (const p of currentAgents.files) {
    if (skillExpected.has(p)) continue;
    const abs = join(ROOT, p);
    assertUnderAgentsSkills(abs);
    rmSync(abs);
    pruneEmptyDirs(dirname(abs));
    deleted++;
  }

  // ---- .codex/agents/*.toml ----
  const claudeAgents = source.listClaudeAgents();
  if (claudeAgents.symlinks.length) {
    console.error(`[sync-codex-compat] ✗ ${CLAUDE_AGENTS_DIR} 配下に symlink がある。書き込みを中止:`);
    for (const p of claudeAgents.symlinks) console.error(`  - ${p}`);
    return 1;
  }
  const agentExpected = new Map();
  for (const a of claudeAgents.entries) {
    const built = buildAgentToml(a.path, a.content);
    if (built.error) {
      errors.push({ type: 'agent-frontmatter', path: a.path });
      console.error(`  - agent ${built.error}: ${a.path}`);
      continue;
    }
    agentExpected.set(`${CODEX_AGENTS_DIR}/${built.name}.toml`, built.content);
  }
  for (const [p, expected] of agentExpected) {
    const abs = join(ROOT, p);
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    if (current === expected) {
      unchanged++;
      continue;
    }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, expected, 'utf8');
    written++;
  }
  const currentCodexAgents = source.listCodexAgentFiles();
  for (const p of currentCodexAgents.files) {
    if (agentExpected.has(p)) continue;
    const abs = join(ROOT, p);
    if (relative(join(ROOT, CODEX_AGENTS_DIR), abs).startsWith('..')) throw new Error(`削除対象が ${CODEX_AGENTS_DIR} 配下ではない: ${abs}`);
    rmSync(abs);
    deleted++;
  }

  // ---- .codex/hooks.json ----
  const settingsText = source.readClaudeSettings();
  const hooksBuilt = settingsText === null ? { content: null, errors: [`${CLAUDE_SETTINGS} が無い`] } : buildCodexHooks(settingsText);
  if (hooksBuilt.content === null || hooksBuilt.errors.length) {
    console.error(`[sync-codex-compat] ✗ ${CODEX_HOOKS_JSON} を生成できない:`);
    for (const e of hooksBuilt.errors) console.error(`  - ${e}`);
    return 1;
  }
  const hooksAbs = join(ROOT, CODEX_HOOKS_JSON);
  const hooksCurrent = existsSync(hooksAbs) ? readFileSync(hooksAbs, 'utf8') : null;
  if (hooksCurrent === hooksBuilt.content) unchanged++;
  else {
    mkdirSync(dirname(hooksAbs), { recursive: true });
    writeFileSync(hooksAbs, hooksBuilt.content, 'utf8');
    written++;
  }

  const agentsMdAbs = join(ROOT, AGENTS_MD);
  const agentsMdCurrent = existsSync(agentsMdAbs) ? readFileSync(agentsMdAbs, 'utf8') : null;
  if (agentsMdCurrent === agentsMdExpected) {
    unchanged++;
  } else {
    writeFileSync(agentsMdAbs, agentsMdExpected, 'utf8');
    written++;
  }

  console.log(`[sync-codex-compat] written=${written} deleted=${deleted} unchanged=${unchanged}`);
  console.log('[sync-codex-compat] 自己検査を実行:');
  const selfCheckExit = runCheck(fsSource());
  if (errors.length) return 1; // frontmatter/重複 が残っている限り --write 自体は非0
  return selfCheckExit;
}

// ---- CLI ---------------------------------------------------------------------------------------

function main() {
  if (process.env.SKIP_CODEX_COMPAT === '1') {
    console.log('[sync-codex-compat] スキップ（SKIP_CODEX_COMPAT=1）');
    return 0;
  }
  const argv = process.argv.slice(2);
  const KNOWN = ['--check', '--write', '--staged'];
  const unknown = argv.filter((a) => !KNOWN.includes(a));
  if (unknown.length) {
    console.error(`[sync-codex-compat] ✗ 未知の引数: ${unknown.join(' ')}`);
    return 1;
  }
  const modes = argv.filter((a) => KNOWN.includes(a));
  if (modes.length > 1) {
    console.error(`[sync-codex-compat] ✗ モードは1つだけ指定可能: ${modes.join(' ')}`);
    return 1;
  }
  const mode = modes[0] || '--check';

  try {
    if (mode === '--write') return runWrite();
    if (mode === '--staged') return runCheck(indexSource());
    return runCheck(fsSource());
  } catch (e) {
    console.error(`[sync-codex-compat] ✗ 予期しないエラー: ${e.stack || e.message}`);
    return 1;
  }
}

process.exit(main());
